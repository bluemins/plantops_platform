export type MessageKey = keyof (typeof messages)["en"];

export function translate(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}) {
  let result: string = messages[locale][key] ?? messages.en[key];
  for (const [name, value] of Object.entries(values)) result = result.replaceAll(`{${name}}`, String(value));
  return result;
}

export function localizedExpiry(locale: Locale, kind: string, days: number | null) {
  const numberLocale = locale === "hi" ? "hi-IN" : locale === "or" ? "or-IN" : "en-IN";
  const number = (value: number) => new Intl.NumberFormat(numberLocale).format(value);
  if (kind === "none") return translate(locale, "noExpiryStatus");
  if (kind === "valid") return translate(locale, "valid");
  if (kind === "today") return translate(locale, "expiresToday");
  if (kind === "soon") return days === 1 ? translate(locale, "expiresInOne") : translate(locale, "expiresIn", { days: number(days ?? 0) });
  return days === -1 ? translate(locale, "expiredDay") : translate(locale, "expiredDays", { days: number(Math.abs(days ?? 0)) });
}

export function localizedStage(locale: Locale, stage: string) {
  const keys: Record<string, MessageKey> = { d30: "stageD30", d7: "stageD7", d1: "stageD1", d0: "stageD0" };
  const numberLocale = locale === "hi" ? "hi-IN" : locale === "or" ? "or-IN" : "en-IN";
  const weeks = new Intl.NumberFormat(numberLocale).format(Number(stage.replace("expired_w", "")));
  return keys[stage] ? translate(locale, keys[stage]!) : translate(locale, "expiredWeeks", { weeks });
}

export function localizedReminderStatus(locale: Locale, status: string) {
  const keys: Record<string, MessageKey> = { sent: "sent", pending: "sending", skipped: "notSent", failed: "failed" };
  return keys[status] ? translate(locale, keys[status]!) : status;
}

const intlLocale: Record<Locale, string> = { en: "en-IN", hi: "hi-IN", or: "or-IN" };

export function localizedDate(locale: Locale, ymd: string) {
  const [year, month, day] = ymd.split("-").map(Number);
  return new Intl.DateTimeFormat(intlLocale[locale], { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" })
    .format(new Date(Date.UTC(year!, month! - 1, day!)));
}

export function localizedDateTime(locale: Locale, iso: string) {
  return new Intl.DateTimeFormat(intlLocale[locale], { dateStyle: "medium", timeStyle: "short", timeZone: "Asia/Kolkata" }).format(new Date(iso));
}
